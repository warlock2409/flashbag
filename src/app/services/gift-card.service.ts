import { HttpClient } from '@angular/common/http';
import { inject, Injectable } from '@angular/core';
import { Observable } from 'rxjs';
import { environment } from 'src/environments/environment';
import { ServiceResponse } from '../app.component';

export interface UserCredit {
  userId: number;
  active: boolean;
  availableBalancePaise: number;
  totalEarnedPaise: number;
  totalRedeemedPaise: number;
}

export interface GiftCardStatusCount {
  shopCode: string;
  totalGiftCards: number;
  countByStatus: { ISSUED: number; CLAIMED: number; EXPIRED: number; REVOKED: number };
}

@Injectable({
  providedIn: 'root'
})
export class GiftCardService {

  Http = inject(HttpClient);

  getTotalCredit(userId: number): Observable<ServiceResponse<UserCredit>> {
    const url = `${environment.apiUrl}/GiftCard/total-credit/user/${userId}`;
    return this.Http.get<ServiceResponse<UserCredit>>(url);
  }

  /** Gift cards generated by a shop, counted per status. */
  getShopStatusCount(shopCode: string): Observable<ServiceResponse<GiftCardStatusCount>> {
    const url = `${environment.apiUrl}/GiftCard/shop/${shopCode}/status-count`;
    return this.Http.get<ServiceResponse<GiftCardStatusCount>>(url);
  }
}
